package juegos;

/** Resultado de comparar un intento con el número secreto en "El mayor y menor". */
public enum Pista {
    /** El número secreto es mayor que el número ingresado. */
    MAYOR,
    /** El número secreto es menor que el número ingresado. */
    MENOR,
    /** El número ingresado coincide con el número secreto. */
    ACIERTO
}
